export const resolveIcon = (iconName: any) => {
  if (!iconName) return HelpCircle;
  if (typeof iconName === 'function') return iconName;
  if (typeof iconName === 'object') return HelpCircle;
  return IconMap[iconName] || HelpCircle;
};
